function detectLang() {
  const fromUrl = new URLSearchParams(location.search).get('lang');
  if (fromUrl && I18N[fromUrl]) return fromUrl;
  const stored = localStorage.getItem('ob-lang');
  if (stored && I18N[stored]) return stored;
  const nav = (navigator.language || navigator.languages?.[0] || 'es').toLowerCase();
  if (nav.startsWith('pt')) return 'pt';
  if (nav.startsWith('en')) return 'en';
  return 'es';
}

function syncLangLinks(lang) {
  document.querySelectorAll('.lang-link').forEach((a) => {
    let href = a.getAttribute('href');
    if (!href || href.startsWith('#')) return;
    const page = href.split('?')[0];
    a.href = page + '?lang=' + lang;
  });
}

function applyLang(lang) {
  const t = I18N[lang];
  document.documentElement.lang = lang;
  
  // Set title dynamically based on page
  if (document.body.classList.contains('page-cumashop')) {
    document.title = t.docTitleCuma;
  } else if (document.body.classList.contains('page-ledexsoft')) {
    document.title = t.docTitleLedex;
  } else {
    document.title = t.docTitlePriv;
  }

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  document.querySelectorAll('.lang-switch button').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  localStorage.setItem('ob-lang', lang);
  syncLangLinks(lang);
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.lang-switch button').forEach((btn) => {
    btn.addEventListener('click', () => applyLang(btn.dataset.lang));
  });

  applyLang(detectLang());

  // Scroll Animations
  const observerOptions = {
    root: null,
    rootMargin: '0px',
    threshold: 0.1
  };

  const observer = new IntersectionObserver((entries, observer) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('fade-in-visible');
        observer.unobserve(entry.target);
      }
    });
  }, observerOptions);

  document.querySelectorAll('.feature-card, .glass-panel, .hero-content, .hero-visual, .faq-section').forEach(el => {
    el.classList.add('fade-in-hidden');
    observer.observe(el);
  });

  // FAQ Logic
  document.querySelectorAll('.faq-question').forEach(q => {
    q.addEventListener('click', () => {
      const parent = q.parentElement;
      parent.classList.toggle('active');
    });
  });
});
